#!/usr/bin/env python3
"""Throwaway generator: tools/neff-isa-fields.json -> neuron_asm/isa_structs.hpp.

One C++ struct per NEURON_ISA_TPB_* struct (all ISA versions), every field a
constexpr descriptor {offset, size_bits}. Instruction storage is a 64-byte
std::array; accessors read/write little-endian bit fields at runtime (the
field map uses byte offsets + bit sizes, unaligned is normal).
"""
import json
import re
from pathlib import Path

SRC = Path(__file__).parent.parent / "neff-isa-fields.json"
OUT = Path(__file__).parent / "isa_structs.hpp"


def cpp_ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def main():
    fields = json.loads(SRC.read_text())
    structs = {}  # qualname -> [(field, off, size)]
    for qual, fd in fields.items():
        m = re.match(r"(?P<ver>common|v1|v2|v3)\.NEURON_ISA_TPB_(?P<name>[A-Z0-9_]+)_STRUCT\.(?P<f>.+)", qual)
        if not m:
            continue
        off = fd["off"]
        size = fd["size"]
        if off is None or size is None or off < 0:
            continue
        structs.setdefault((m.group("ver"), m.group("name")), []).append(
            (m.group("f"), off, size))

    out = []
    out.append("// GENERATED by gen_structs.py from tools/neff-isa-fields.json - do not edit.")
    out.append("#pragma once")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("#include <cstddef>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace nisa {")
    out.append("")
    out.append("constexpr size_t kInstBytes = 64;  // engines fetch 64B (INST_NBYTES)")
    out.append("")
    out.append("// Runtime bit-field access (fields are unaligned; little-endian).")
    out.append("inline uint64_t load_bits(const uint8_t* p, size_t off, size_t size) {")
    out.append("    uint64_t v = 0;")
    out.append("    for (size_t i = 0; i < size; ++i) {")
    out.append("        size_t bit = off + i;")
    out.append("        v |= uint64_t((p[bit >> 3] >> (bit & 7)) & 1) << i;")
    out.append("    }")
    out.append("    return v;")
    out.append("}")
    out.append("")
    out.append("inline void store_bits(uint8_t* p, size_t off, size_t size, uint64_t v) {")
    out.append("    for (size_t i = 0; i < size; ++i) {")
    out.append("        size_t bit = off + i;")
    out.append("        uint8_t m = uint8_t(1u << (bit & 7));")
    out.append("        if ((v >> i) & 1) p[bit >> 3] |= m; else p[bit >> 3] &= uint8_t(~m);")
    out.append("    }")
    out.append("}")
    out.append("")

    def emit(ver, name, fl):
        struct_name = f"{cpp_ident(ver)}_{cpp_ident(name)}"
        out.append(f"// {ver}.NEURON_ISA_TPB_{name}_STRUCT ({len(fl)} fields)")
        out.append(f"struct {struct_name} {{")
        out.append("    std::array<uint8_t, kInstBytes> b{};")
        out.append(f"    static constexpr std::string_view kName = \"{ver}.{name}\";")
        seen = {}
        for f, off, size in fl:
            ident = cpp_ident(f)
            if ident in seen:
                continue  # alias (same field name, first wins)
            seen[ident] = (off, size)
        for ident, (off, size) in seen.items():
            out.append(f"    static constexpr size_t k_{ident}_off = {off};")
            out.append(f"    static constexpr size_t k_{ident}_bits = {size};")
        out.append("")
        for ident, (off, size) in seen.items():
            out.append(f"    uint64_t get_{ident}() const {{ return load_bits(b.data(), {off}, {size}); }}")
            out.append(f"    void set_{ident}(uint64_t v) {{ store_bits(b.data(), {off}, {size}, v); }}")
        out.append("};")
        out.append("")

    for (ver, name), fl in sorted(structs.items()):
        emit(ver, name, fl)

    out.append("}  // namespace nisa")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(structs)} structs")


if __name__ == "__main__":
    main()
