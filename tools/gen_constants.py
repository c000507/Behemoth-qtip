"""Generate src/qtip_constants.hpp from the QTIP reference code (github.com/Cornell-RelaxML/qtip):
  - the non-power-of-two Hadamard factors hadK for K in {12, 20, 28, 36, 52, 60, 108, 116, 124, 140, 156, 172}
    (lib/utils/matmul_had.py get_hadK), stored as +-1 int8
  - the HYB ('quantlut_sym', tlut_bits=9, V=2) tunable LUT, built exactly like quantbench/qtip_shim.py
    (k-means of 2^20 2-D Gaussians, 512 centroids, seed 0, std-normalised * 0.9682458365518543).
    Also writes it to /tmp/kmeans_9_2.pt (the path the reference reads) unless --no_tmp.
Usage: QTIP_DIR=/path/to/qtip python tools/gen_constants.py --out src/qtip_constants.hpp
"""
import argparse, os, struct, sys
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import qtip_shim  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--out", default=os.path.join(HERE, "..", "src", "qtip_constants.hpp"))
ap.add_argument("--no_tmp", action="store_true")
args = ap.parse_args()

qtip_shim.install()  # builds /tmp/kmeans_9_2.pt if missing (deterministic, seed 0)
from lib.utils import matmul_had  # noqa: E402

tlut = torch.load("/tmp/kmeans_9_2.pt").float()
assert tlut.shape == (512, 2)

Ks = [172, 156, 140, 124, 116, 108, 60, 52, 36, 28, 20, 12]
lines = ["// Generated by tools/gen_constants.py from the QTIP reference code. Do not edit.",
         "#pragma once", "#include <cstdint>", "namespace qtip {"]
for K in Ks:
    H = getattr(matmul_had, f"get_had{K}")()
    assert H.shape == (K, K) and set(H.unique().tolist()) <= {-1.0, 1.0}
    assert torch.allclose(H @ H.T, K * torch.eye(K))
    vals = ",".join(str(int(v)) for v in H.flatten().tolist())
    lines.append(f"inline constexpr int8_t kHad{K}[{K * K}] = {{{vals}}};")
lines.append("// order of the divisibility checks in get_hadK()")
lines.append(f"inline constexpr int kHadOrder[{len(Ks)}] = {{{','.join(map(str, Ks))}}};")
lines.append("inline const int8_t* had_table(int K) { switch (K) {")
for K in Ks:
    lines.append(f"  case {K}: return kHad{K};")
lines.append("  default: return nullptr; } }")
bits = [struct.unpack("<I", struct.pack("<f", v))[0] for v in tlut.flatten().tolist()]
lines.append("// HYB tlut [512][2] fp32 bit patterns (k-means, seed 0, as quantbench/qtip_shim.py)")
lines.append(f"inline constexpr uint32_t kTlutF32Bits[1024] = {{{','.join(hex(b) for b in bits)}}};")
lines.append("}  // namespace qtip")
with open(args.out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", args.out, "tlut std", tlut.std(unbiased=False).item())
