PROLOGUE = bytes.fromhex(EW_PE0)  # [177][pad][204][pad] universal

def synth_streams(n: int, scale: float):
    """-> {engine.bin: bytes} fully synthesized for (n, scale)."""
    P = (n + 127) // 128
    if n <= 0 or P > 16383:
        raise ValueError(f"n={n} out of range (1..2098176)")
    if n <= 128:
        dve = bytearray(bytes.fromhex(EW_B_DVE0))
        # u16 @226 = n, f32 @232 = scale (inside op10 @224)
        struct.pack_into("<H", dve, 226, n)
        struct.pack_into("<f", dve, 232, scale)
        act = PROLOGUE
        pool = bytearray(bytes.fromhex(EW_B_POOL))
        for base in (160, 224, 288):
            struct.pack_into("<H", pool, base, n)
            struct.pack_into("<H", pool, base + 24, n)
        return {"PE0.bin": PROLOGUE, "SP0.bin": PROLOGUE,
                "DVE0.bin": bytes(dve), "Activation0.bin": act,
                "Pool0.bin": bytes(pool)}
    neg4P, neg8P = 65536 - 4 * P, 65536 - 8 * P
    dve = bytearray(bytes.fromhex(EW_A_DVE0))
    struct.pack_into("<H", dve, 218, P)
    struct.pack_into("<H", dve, 224, neg8P & 0xFFFF)
    struct.pack_into("<H", dve, 234, P)
    struct.pack_into("<H", dve, 250, P)
    act = bytearray(bytes.fromhex(EW_A_ACT))
    struct.pack_into("<f", act, 228, scale)
    struct.pack_into("<H", act, 208, neg4P & 0xFFFF)
    struct.pack_into("<H", act, 218, P)
    struct.pack_into("<H", act, 250, P)
    pool = bytearray(bytes.fromhex(EW_A_POOL))
    struct.pack_into("<H", pool, 152, 4 * P)
    struct.pack_into("<H", pool, 164, 4 * P)
    struct.pack_into("<H", pool, 168, neg4P & 0xFFFF)
    struct.pack_into("<H", pool, 188, 4 * P)
    struct.pack_into("<H", pool, 216, 4 * P)
    struct.pack_into("<H", pool, 228, 4 * P)   # slot224+4 (y-out desc)
    struct.pack_into("<H", pool, 232, neg8P & 0xFFFF)
    struct.pack_into("<H", pool, 252, 4 * P)
    struct.pack_into("<H", pool, 292, 4 * P)   # slot288+4 (y-out rearm)
    struct.pack_into("<H", pool, 304, 4 * P)
    struct.pack_into("<H", pool, 316, 4 * P)
    return {"PE0.bin": PROLOGUE, "SP0.bin": PROLOGUE,
            "DVE0.bin": bytes(dve), "Activation0.bin": bytes(act),
            "Pool0.bin": bytes(pool)}
